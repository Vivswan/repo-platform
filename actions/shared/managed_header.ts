// DEPENDENCY-FREE ZONE (see grammar.ts): node builtins and zone-internal imports only.

import { MANAGED_HEADER_PATTERN } from "./platform.ts";

/** Only the first lines are a header, and only comment lines count: a string literal or a shell `echo` carrying the managed sentence is code, so a repo-owned file cannot exempt itself by printing it. */
const HEADER_LINES = 10;

/** A comment line in any language the fleet writes, by its opening token. */
export const COMMENT_LINE = /^\s*(#|\/\/|\/\*|\*|<!--|--|;|%|\{#|"""|''')/;

export function headerLines(text: string): string[] {
  return text.split("\n", HEADER_LINES);
}

/** Only comment lines count and only these phrasings match; a generator's path is no signal: hand-written headers name the generators they serve. "do not edit" in a string literal is no header; "copies generated from the manifests" matches no phrasing. */
const GENERATED_HEADER =
  /\b(generated by|auto-?generated|this file is generated|generated file|do not edit)\b/i;

/** A file the platform's sync writes; the repository that holds it cannot fix it, so a check skips and counts it. */
export function isManaged(text: string): boolean {
  return headerLines(text).some(
    (line) => COMMENT_LINE.test(line) && MANAGED_HEADER_PATTERN.test(line),
  );
}

/** A file whose header declares it generated; a check skips it, since the generator is what to fix. */
export function isGenerated(text: string): boolean {
  return headerLines(text).some((line) => COMMENT_LINE.test(line) && GENERATED_HEADER.test(line));
}
